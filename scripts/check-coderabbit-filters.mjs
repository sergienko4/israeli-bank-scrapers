#!/usr/bin/env node
/**
 * Assert that CodeRabbit's exclusion filters only ever skip files we do not
 * write by hand.
 *
 * Why this script exists: `.coderabbit.yaml` states its own contract in the
 * comment above `path_filters` — the list exists to skip "generated content
 * the maintainer already audits via husky gates". Every entry was written to
 * name a build artifact. But a glob is matched against the whole path, so an
 * unanchored `**\/lib/**` means "a directory called `lib` ANYWHERE", not "the
 * `lib/` we build into". `scripts/decoupling-metrics/lib/*.mjs` — four
 * hand-written modules — were silently excluded from every review since the
 * filter landed.
 *
 * That failure is invisible by construction. A filter that is too broad
 * produces no error, no warning, and no missing output: it produces a review
 * that simply says less. Nobody notices the comment that was never written,
 * which is why this has to be a gate rather than a convention.
 *
 * The rule enforced: an exclusion may match a git-tracked file ONLY if it is
 * named in `DELIBERATE` below with a reason. Anything else must match zero
 * tracked files — build output is untracked, so a hit means the glob reaches
 * further than its author intended.
 *
 * Scope, stated honestly: this proves no filter hides tracked content. It
 * cannot prove the filters cover everything generated — an untracked artifact
 * is invisible to `git ls-files` by definition, and skipping too little only
 * costs tokens. Skipping too much costs review coverage, so that is the
 * direction worth gating.
 *
 * Deliberately dependency-free, for the same reason as
 * `check-node-support.mjs`: a config-only PR can run in a job that never
 * installed `node_modules`, which is precisely the change this gate exists to
 * catch. The glob subset below is therefore hand-rolled — and THROWS on any
 * syntax it does not implement, so an unsupported pattern fails loudly instead
 * of silently matching nothing and reporting success.
 *
 * Usage:
 *   node scripts/check-coderabbit-filters.mjs
 *
 * Exit codes:
 *   0  every exclusion is anchored to untracked or deliberately-skipped content
 *   1  an exclusion hides git-tracked files
 */
import { readFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { exit, stderr, stdout } from 'node:process';

const CONFIG = '.coderabbit.yaml';

/** The `path_filters:` key, and the list items that follow it. */
const FILTER_BLOCK = /^\s*path_filters:\s*$/m;

/** One quoted list entry, ignoring any trailing `# comment`. */
const LIST_ITEM = /^\s*-\s*"([^"]+)"/;

/**
 * Exclusions allowed to match tracked files, each with the reason it is not
 * the bug this gate looks for. Keyed by the pattern exactly as written in
 * the config, so editing the pattern re-opens the question.
 */
const DELIBERATE = new Map([
  ['!package-lock.json', 'lockfile — machine-resolved, reviewing it is noise'],
  ['!CHANGELOG.md', 'generated by release-please from commit subjects'],
  [
    '!.husky/**',
    'hand-written, but deliberately skipped: every hook edit is exercised by ' +
      'the author on the very next commit, which is a stronger signal than a ' +
      'static read of shell',
  ],
]);

/**
 * Abort the run. A too-broad filter is silent in production, so it has to be
 * loud here — a warning would be filtered out of the log it appears in.
 * @param {string} message - Which filter over-reaches, and what it hides.
 * @returns {never}
 */
function fail(message) {
  stderr.write(`check-coderabbit-filters: ${message}\n`);
  exit(1);
}

/**
 * Indentation width of a line, used to detect where the list ends.
 * @param {string} line - Raw line including leading whitespace.
 * @returns {number} Count of leading spaces.
 */
function indentOf(line) {
  return line.length - line.trimStart().length;
}

/**
 * Exclusion patterns declared in the config, in document order.
 *
 * Reads until the block ends rather than until the first unrecognised line:
 * blank lines and comments sit *inside* the list, so skipping them blindly
 * would let the scan run past `path_filters:` and absorb a later sequence.
 * The list's own indentation is the boundary — anything shallower has left
 * the block. A list item it cannot parse aborts rather than ending the scan,
 * because stopping early would silently drop every filter below it, which is
 * this gate's own version of the bug it exists to catch.
 * @returns {string[]} Entries beginning with `!`, quotes stripped.
 */
function exclusions() {
  const text = readFileSync(CONFIG, 'utf8');
  const block = FILTER_BLOCK.exec(text);
  if (!block) fail(`${CONFIG}: no \`path_filters:\` key found`);
  const found = [];
  let depth = null;
  for (const line of text.slice(block.index + block[0].length).split('\n')) {
    if (line.trim() === '') continue;
    if (depth !== null && indentOf(line) < depth) break;
    if (line.trimStart().startsWith('#')) continue;
    const item = LIST_ITEM.exec(line);
    if (!item) {
      if (/^\s*-\s/.test(line)) {
        fail(`${CONFIG}: unparseable \`path_filters\` entry ${line.trim()} — this script reads double-quoted scalars only. Quote it, or teach this script the syntax; silently skipping it would hide the very filters it checks.`);
      }
      break;
    }
    depth ??= indentOf(line);
    if (item[1].startsWith('!')) found.push(item[1]);
  }
  if (found.length === 0) fail(`${CONFIG}: \`path_filters:\` declares no \`!\` exclusions`);
  return found;
}

/**
 * Translate one glob segment — a run between `/` separators — into a RegExp
 * fragment that cannot cross a separator.
 * @param {string} segment - Segment text, never containing `/`.
 * @returns {string} Fragment matching exactly that segment.
 */
function segmentToRegExp(segment) {
  let out = '';
  for (const char of segment) {
    if ('?[]{}()+@!'.includes(char)) {
      fail(`${CONFIG}: pattern segment "${segment}" uses unsupported glob syntax "${char}" — extend this script before using it`);
    }
    out += char === '*' ? '[^/]*' : char.replace(/[.*+?^${}()|[\]\\-]/g, '\\$&');
  }
  return out;
}

/**
 * Translate the glob subset the config actually uses into a RegExp.
 *
 * Works per path segment rather than per character, because the two `*`
 * forms differ only in whether they may cross a `/` — a distinction that is
 * easy to state segment-wise and easy to get wrong character-wise. `**`
 * spans any number of segments; `*` stays inside one; everything else is a
 * literal, and unsupported metacharacters abort.
 * @param {string} glob - Pattern without its leading `!`.
 * @returns {RegExp} Anchored matcher for a repo-relative path.
 */
function globToRegExp(glob) {
  const segments = glob.split('/');
  let out = '';
  segments.forEach((segment, index) => {
    const last = index === segments.length - 1;
    if (segment === '**') {
      out += last ? '(?:.*)?' : '(?:[^/]*/)*';
      return;
    }
    out += segmentToRegExp(segment) + (last ? '' : '/');
  });
  return new RegExp(`^${out}$`);
}

/**
 * Every path git tracks, which is the set a reviewer could be asked to read.
 *
 * Reports a git failure through `fail()` rather than letting the exception
 * escape: an unhandled stack trace in a pre-commit log reads as a crash in
 * the gate, when the actual cause is the environment it was run from.
 * @returns {string[]} Repo-relative paths.
 */
function trackedFiles() {
  try {
    const out = execFileSync('git', ['ls-files'], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
    return out.split('\n').filter((line) => line !== '');
  } catch (error) {
    return fail(`could not list tracked files — run this from the repository root (${error.message.split('\n')[0]})`);
  }
}

const tracked = trackedFiles();
const declared = exclusions();
const offenders = [];
let deliberate = 0;

for (const pattern of declared) {
  const matcher = globToRegExp(pattern.slice(1));
  const hits = tracked.filter((path) => matcher.test(path));
  if (hits.length === 0) continue;
  if (DELIBERATE.has(pattern)) {
    deliberate += 1;
    continue;
  }
  offenders.push({ pattern, hits });
}

if (offenders.length > 0) {
  const detail = offenders
    .map(({ pattern, hits }) => {
      const shown = hits.slice(0, 5).join('\n      ');
      const more = hits.length > 5 ? `\n      …and ${hits.length - 5} more` : '';
      return `  "${pattern}" hides ${hits.length} tracked file(s):\n      ${shown}${more}`;
    })
    .join('\n');
  fail(
    `${CONFIG}: exclusion filters hide hand-written source from review.\n${detail}\n` +
      '  Anchor the pattern to the generated directory it means (e.g. "!lib/**"\n' +
      '  rather than "!**/lib/**"), or add it to DELIBERATE in this script with\n' +
      '  the reason it is safe to skip.',
  );
}

stdout.write(
  `check-coderabbit-filters: ${declared.length} exclusions, ` +
    `${deliberate} deliberate, 0 hiding tracked source ✓\n`,
);
exit(0);
