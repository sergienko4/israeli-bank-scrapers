#!/usr/bin/env node
/**
 * Writes `src/Scrapers/Pipeline/Mediator/Browser/BrowserStackConfig.ts` from
 * `browser-stack.json`, so runtime code reads the tested Camoufox tag and
 * playwright-core minor from the manifest rather than from a copied literal.
 *
 * Usage: `npm run browser-stack:gen` after editing the manifest. The run is
 * idempotent: an unchanged manifest leaves the file untouched. The
 * browser-stack gate (`npm run lint:browser-stack`) fails GENERATED-STALE in
 * gate mode when the committed file differs from what this would write.
 *
 * Exit codes: 0 written or already current · 2 the manifest is invalid
 * (MANIFEST-INVALID lines on stderr; nothing is written).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import process from 'node:process';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { issueLine, loadManifest } from './manifest.mjs';

/** Repo-relative path of the generated module. */
export const GENERATED_REL = 'src/Scrapers/Pipeline/Mediator/Browser/BrowserStackConfig.ts';

const ROOT = fileURLToPath(new URL('../../', import.meta.url));

/** Production I/O; tests override any member. */
const DEFAULT_IO = Object.freeze({
  manifestPath: join(ROOT, 'browser-stack.json'),
  generatedPath: join(ROOT, GENERATED_REL),
  stdout: (/** @type {string} */ text) => process.stdout.write(text),
  stderr: (/** @type {string} */ text) => process.stderr.write(text),
});

/** Default path of the generated module, for the gate. */
export const GENERATED_PATH = DEFAULT_IO.generatedPath;

/** Fixed head of the generated module. */
const HEADER = Object.freeze([
  '/**',
  ' * GENERATED by `npm run browser-stack:gen` from `browser-stack.json`. Do not',
  ' * edit: change the manifest, then regenerate. The browser-stack gate fails',
  ' * GENERATED-STALE when this file and the manifest disagree.',
  ' */',
  '',
]);

/**
 * Source of the generated module. The manifest validator restricts both
 * values to version characters, so they need no escaping.
 *
 * @param {{ camoufox: { tag: string }, playwrightCore: { testedMinor: string } }} manifest - Valid manifest.
 * @returns {string} TypeScript source ending in a newline.
 */
export function renderConfig(manifest) {
  const body = [
    '/** Camoufox release tag this package is tested on. */',
    `export const TESTED_CAMOUFOX_TAG = '${manifest.camoufox.tag}';`,
    '',
    '/** playwright-core minor (`major.minor`) this package is tested on. */',
    `export const TESTED_PLAYWRIGHT_MINOR = '${manifest.playwrightCore.testedMinor}';`,
  ];
  return `${[...HEADER, ...body].join('\n')}\n`;
}

/**
 * Whether the file at `path` differs from the render of `manifest`. A
 * missing file is stale; any other read error propagates.
 *
 * @param {import('./manifest.d.mts').IValidManifest} manifest - Valid manifest.
 * @param {string} path - Path of the generated module.
 * @returns {boolean} True when regeneration would change the file.
 */
export function isGeneratedStale(manifest, path) {
  try {
    return readFileSync(path, 'utf8') !== renderConfig(manifest);
  } catch (error) {
    if (/** @type {NodeJS.ErrnoException} */ (error).code === 'ENOENT') return true;
    throw error;
  }
}

/**
 * Report an invalid manifest.
 *
 * @param {import('./manifest.d.mts').ManifestIssue[]} issues - Every finding.
 * @param {{ stderr: (text: string) => unknown }} io - Error sink.
 * @returns {2} Exit code.
 */
function reportInvalid(issues, io) {
  io.stderr(`${issues.map(issueLine).join('\n')}\n`);
  return 2;
}

/**
 * Write the module when it is stale.
 *
 * @param {Partial<typeof DEFAULT_IO>} [overrides] - Test paths and sinks.
 * @returns {0 | 2} 0 written or current; 2 invalid manifest.
 */
export function generate(overrides = {}) {
  const io = { ...DEFAULT_IO, ...overrides };
  const { manifest, issues } = loadManifest(io.manifestPath);
  if (manifest === undefined) return reportInvalid(issues, io);
  const stale = isGeneratedStale(manifest, io.generatedPath);
  if (stale) writeFileSync(io.generatedPath, renderConfig(manifest));
  io.stdout(`${GENERATED_REL} ${stale ? 'written' : 'already current'}\n`);
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  process.exitCode = generate();
}
